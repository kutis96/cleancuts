// Package gcode renders machine-independent moves into a generic,
// dialect-neutral G-code stream. It is the default post-processor: given a
// moves.Path it emits G0/G1/G2/G3 motions plus spindle, coolant, and
// program-end codes.
//
// Machine-specific post-processing (GRBL, LinuxCNC, Fanuc, ...) is a separate,
// configurable layer that composes over this one, driven by the machine JSON
// config (see docs/gcode.md and schemas/machine.schema.json). Keeping the
// generic emitter separate means a machine layer only ever varies the dialect
// and framing, never the geometry — which is what keeps coordinate bugs far
// from the core.
package gcode

import (
	"fmt"
	"math"
	"strings"

	"github.com/kutis96/cleancuts/internal/kernel"
	"github.com/kutis96/cleancuts/internal/moves"
)

// Options configure the generic G-code emitter.
type Options struct {
	// HeaderLines and FooterLines are emitted verbatim at the start/end.
	HeaderLines []string
	FooterLines []string
	// UseArms controls whether arc moves are emitted as G2/G3 (true) or
	// tessellated into G1 line segments (false).
	UseArms bool
	// ArcTolDeg is the maximum arc segment angle (degrees) when UseArms is
	// false.
	ArcTolDeg float64
	// CommentPrefix prefixes block comments (default ";").
	CommentPrefix string
	// CoordPrecision is the number of decimal places for coordinates
	// (default 4 = 1 µm). G-code is a decimal text protocol for machines
	// with finite resolution — formatting is a post-processing concern
	// (ADR-002), and it also absorbs the last ulps of the core's
	// float64 arithmetic so the output stays clean.
	CoordPrecision int
	// SpindleStart / SpindleStop / ProgramEnd are M-codes (defaults 3/5/2).
	SpindleStart int
	SpindleStop  int
	ProgramEnd   int
	// CoolantOn / CoolantOff are M-codes for flood (defaults 8/9).
	CoolantOn  int
	CoolantOff int
}

// DefaultOptions returns sensible defaults.
func DefaultOptions() Options {
	return Options{
		UseArms:        true,
		ArcTolDeg:      5,
		CommentPrefix:  ";",
		CoordPrecision: 4,
		SpindleStart:   3,
		SpindleStop:    5,
		ProgramEnd:     2,
		CoolantOn:      8,
		CoolantOff:     9,
	}
}

// Emit renders a single path to a G-code program (a convenience over
// EmitProgram; ADR-019 §4 keeps the v0.1 surface).
func Emit(p moves.Path, o Options) (string, error) {
	return EmitProgram(moves.Program{ID: p.ID, Name: p.Name, Paths: []moves.Path{p}}, o)
}

// EmitProgram renders a whole program (ADR-019 §4): one header — spindle
// speed (the max across paths) and coolant (if any path wants it) — then
// the paths in order, each under a comment, then one footer (coolant off,
// spindle off, program end). Link paths emit like any other: their moves
// are just moves, so no linking logic lives here.
func EmitProgram(p moves.Program, o Options) (string, error) {
	if err := p.Validate(); err != nil {
		return "", fmt.Errorf("gcode: %w", err)
	}
	if o.CommentPrefix == "" {
		o.CommentPrefix = ";"
	}
	if o.ArcTolDeg <= 0 {
		o.ArcTolDeg = 5
	}
	if o.CoordPrecision <= 0 {
		o.CoordPrecision = 4
	}

	spindle := 0.0
	coolantOn := false
	for _, path := range p.Paths {
		if s := maxSpindle(path); s > spindle {
			spindle = s
		}
		if wantsCoolant(path) {
			coolantOn = true
		}
	}

	var b strings.Builder
	w := &writer{b: &b, o: o}

	for _, h := range o.HeaderLines {
		w.line(h)
	}
	w.comment("Generated by CleanCuts (generic post-processor)")
	if p.Name != "" {
		w.comment(p.Name)
	}
	if spindle > 0 {
		w.line(fmt.Sprintf("S%g", spindle))
		w.line(fmt.Sprintf("M%d", o.SpindleStart))
	}
	if coolantOn {
		w.line(fmt.Sprintf("M%d", o.CoolantOn))
	}

	for _, path := range p.Paths {
		w.comment(path.Name)
		for _, m := range path.Moves {
			w.comment(m.Comment)
			if err := writeMove(w, m); err != nil {
				return "", fmt.Errorf("gcode: path %q: %w", path.ID, err)
			}
		}
	}

	if coolantOn {
		w.line(fmt.Sprintf("M%d", o.CoolantOff))
	}
	if spindle > 0 {
		w.line(fmt.Sprintf("M%d", o.SpindleStop))
	}
	for _, f := range o.FooterLines {
		w.line(f)
	}
	w.line(fmt.Sprintf("M%d", o.ProgramEnd))

	return b.String(), nil
}

// writer accumulates G-code lines with a consistent comment prefix.
type writer struct {
	b *strings.Builder
	o Options
}

func (w *writer) line(s string) {
	if s == "" {
		return
	}
	w.b.WriteString(s)
	w.b.WriteByte('\n')
}

func (w *writer) comment(s string) {
	if s == "" {
		return
	}
	w.line(w.o.CommentPrefix + " " + s)
}

func writeMove(w *writer, m moves.Move) error {
	switch m.Kind {
	case moves.KindRapid:
		w.line(fmt.Sprintf("G0 %s", w.coords(m)))
	case moves.KindLinear:
		w.line(fmt.Sprintf("G1 %s F%g", w.coords(m), m.Feed))
	case moves.KindArcCCW, moves.KindArcCW:
		code := "G3"
		if m.Kind == moves.KindArcCW {
			code = "G2"
		}
		if !w.o.UseArms {
			return tessellateArc(w, m)
		}
		// I/J are centre offsets relative to the arc start point, at the
		// same precision as the coordinates (they are coordinates too).
		cx := m.Center.X - m.From.X
		cy := m.Center.Y - m.From.Y
		w.line(fmt.Sprintf("%s %s I%s J%s F%g", code, w.coords(m), w.fmt(cx), w.fmt(cy), m.Feed))
	default:
		return fmt.Errorf("gcode: unknown move kind %q", m.Kind)
	}
	return nil
}

func (w *writer) coords(m moves.Move) string {
	return fmt.Sprintf("X%s Y%s Z%s", w.fmt(m.To.X), w.fmt(m.To.Y), w.fmt(m.To.Z))
}

// fmt renders a coordinate at the configured precision, trimming trailing
// zeros (so "X-5", not "X-5.0000") and normalising -0 to 0.
func (w *writer) fmt(v float64) string {
	s := fmt.Sprintf("%.*f", w.o.CoordPrecision, v)
	s = strings.TrimRight(s, "0")
	s = strings.TrimRight(s, ".")
	if s == "-0" {
		s = "0"
	}
	return s
}

// tessellateArc approximates an arc with G1 line segments no wider than
// o.ArcTolDeg, for controllers without reliable G2/G3 support.
func tessellateArc(w *writer, m moves.Move) error {
	r := m.Center.Dist(m.From)
	if r <= 0 {
		return fmt.Errorf("gcode: cannot tessellate a degenerate arc")
	}
	a0 := math.Atan2(m.From.Y-m.Center.Y, m.From.X-m.Center.X)
	a1 := math.Atan2(m.To.Y-m.Center.Y, m.To.X-m.Center.X)
	var sweep float64
	if m.CW {
		sweep = -kernel.NormalizeAngle(a0 - a1)
	} else {
		sweep = kernel.NormalizeAngle(a1 - a0)
	}
	step := w.o.ArcTolDeg * math.Pi / 180
	steps := int(math.Ceil(math.Abs(sweep) / step))
	if steps < 1 {
		steps = 1
	}
	for i := 1; i <= steps; i++ {
		t := float64(i) / float64(steps)
		theta := a0 + t*sweep
		x := m.Center.X + r*math.Cos(theta)
		y := m.Center.Y + r*math.Sin(theta)
		w.line(fmt.Sprintf("G1 X%s Y%s Z%s F%g", w.fmt(x), w.fmt(y), w.fmt(m.To.Z), m.Feed))
	}
	return nil
}

func maxSpindle(p moves.Path) float64 {
	var s float64
	for _, m := range p.Moves {
		if m.Spindle > s {
			s = m.Spindle
		}
	}
	return s
}

func wantsCoolant(p moves.Path) bool {
	for _, m := range p.Moves {
		switch m.Coolant {
		case moves.CoolantFlood, moves.CoolantMist, moves.CoolantThrough:
			return true
		}
	}
	return false
}
